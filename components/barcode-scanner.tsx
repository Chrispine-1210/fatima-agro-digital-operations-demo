"use client";

import { useCallback, useEffect, useId, useRef, useState, type FormEvent } from "react";
import "./device-tools.css";

type ScanControls = { stop: () => void };
type NativeDetector = { detect: (image: CanvasImageSource) => Promise<{ rawValue: string }[]> };
type NativeDetectorClass = { new(options: { formats: string[] }): NativeDetector; getSupportedFormats: () => Promise<string[]> };
const supportedFormats = ["code_128", "qr_code", "ean_13", "ean_8", "upc_a", "upc_e", "code_39"];

async function nativeDetector() {
  const Detector = (window as unknown as { BarcodeDetector?: NativeDetectorClass }).BarcodeDetector;
  if (!Detector) return null;
  try {
    const formats = (await Detector.getSupportedFormats()).filter(value => supportedFormats.includes(value));
    // The labels generated by this application require Code 128. Use ZXing if it is unavailable.
    return formats.includes("code_128") ? new Detector({ formats }) : null;
  } catch { return null; }
}

export function BarcodeScanner({ onScan, label = "Scan or enter a barcode" }: { onScan: (value: string) => void; label?: string }) {
  const uid = useId();
  const video = useRef<HTMLVideoElement>(null);
  const stream = useRef<MediaStream | null>(null);
  const controls = useRef<ScanControls | null>(null);
  const frame = useRef<number>(0);
  const generation = useRef(0);
  const onScanRef = useRef(onScan);
  onScanRef.current = onScan;
  const [value, setValue] = useState("");
  const [active, setActive] = useState(false);
  const [busy, setBusy] = useState(false);
  const [message, setMessage] = useState("");
  const [error, setError] = useState("");

  const stop = useCallback(() => {
    generation.current++;
    controls.current?.stop();
    controls.current = null;
    cancelAnimationFrame(frame.current);
    stream.current?.getTracks().forEach(track => track.stop());
    stream.current = null;
    if (video.current) video.current.srcObject = null;
    setActive(false);
    setBusy(false);
  }, []);
  useEffect(() => () => { stop(); }, [stop]);

  function accept(raw: string) {
    const clean = raw.trim();
    if (!clean || clean.length > 160 || /[\u0000-\u001F\u007F]/.test(clean)) { setError("Enter a barcode or SKU with 1 to 160 characters."); return; }
    stop();
    setValue(clean);
    setError("");
    setMessage(`Barcode read: ${clean}. Review the matching product before making changes.`);
    onScanRef.current(clean);
  }

  function manual(event: FormEvent) { event.preventDefault(); accept(value); }

  async function start() {
    stop();
    setError("");
    setMessage("");
    if (!window.isSecureContext || !navigator.mediaDevices?.getUserMedia) { setError("Camera scanning needs HTTPS and a supported browser. Enter a code or choose a barcode image instead."); return; }
    setBusy(true);
    setActive(true);
    const token = generation.current;
    try {
      const detector = await nativeDetector();
      if (token !== generation.current) return;
      if (detector) {
        const media = await navigator.mediaDevices.getUserMedia({ audio: false, video: { facingMode: { ideal: "environment" }, width: { ideal: 1280 } } });
        if (token !== generation.current) { media.getTracks().forEach(track => track.stop()); return; }
        stream.current = media;
        if (!video.current) { stop(); return; }
        video.current.srcObject = media;
        await video.current.play();
        setBusy(false);
        const decode = async () => {
          if (token !== generation.current || !video.current) return;
          try {
            if (video.current.readyState >= 2) {
              const result = await detector.detect(video.current);
              if (token !== generation.current) return;
              if (result[0]?.rawValue) { accept(result[0].rawValue); return; }
            }
          } catch { /* A moving frame can fail to decode. Continue until stopped. */ }
          if (token === generation.current) frame.current = requestAnimationFrame(() => { void decode(); });
        };
        frame.current = requestAnimationFrame(() => { void decode(); });
      } else {
        const { BrowserMultiFormatReader } = await import("@zxing/browser");
        if (token !== generation.current || !video.current) return;
        const reader = new BrowserMultiFormatReader(undefined, { delayBetweenScanAttempts: 250, delayBetweenScanSuccess: 1000 });
        const control = await reader.decodeFromConstraints({ audio: false, video: { facingMode: { ideal: "environment" }, width: { ideal: 1280 } } }, video.current, (result, _error, camera) => {
          if (token !== generation.current) { camera.stop(); return; }
          if (result) { camera.stop(); accept(result.getText()); }
        });
        if (token !== generation.current) { control.stop(); return; }
        controls.current = control;
        setBusy(false);
      }
    } catch (cause) {
      if (token !== generation.current) return;
      stop();
      const name = cause instanceof Error ? cause.name : "";
      setError(name === "NotAllowedError" ? "Camera permission was not granted. Use a barcode image, USB scanner or manual entry." : name === "NotFoundError" ? "No camera was found. Choose a barcode image or enter the code." : "The camera could not start. Close other camera apps and try again, or choose a barcode image.");
    }
  }

  async function fromFile(file: File | undefined) {
    if (!file) return;
    stop(); setError(""); setMessage("");
    if (!file.type.startsWith("image/") || file.size > 12 * 1024 * 1024) { setError("Choose a barcode image smaller than 12 MB."); return; }
    setBusy(true);
    const token = generation.current;
    const url = URL.createObjectURL(file);
    try {
      const image = new Image();
      image.src = url;
      await image.decode();
      const detector = await nativeDetector();
      let result = detector ? (await detector.detect(image))[0]?.rawValue : undefined;
      if (!result) {
        const { BrowserMultiFormatReader } = await import("@zxing/browser");
        result = (await new BrowserMultiFormatReader().decodeFromImageElement(image)).getText();
      }
      if (token === generation.current) accept(result);
    } catch {
      if (token === generation.current) setError("No readable barcode was found. Use a clear, well-lit image showing the entire code, or enter it manually.");
    } finally {
      URL.revokeObjectURL(url);
      if (token === generation.current) setBusy(false);
    }
  }

  return <section className="dt-scanner" aria-label={label}>
    <form className="dt-scan-form" onSubmit={manual}>
      <label htmlFor={`${uid}-code`}>{label}</label>
      <div className="dt-input-action"><input id={`${uid}-code`} autoComplete="off" autoCapitalize="none" spellCheck={false} value={value} maxLength={160} onChange={event => setValue(event.target.value)} placeholder="SKU or barcode - USB scanners can press Enter" /><button type="submit">Find code</button></div>
    </form>
    <div className="dt-actions"><button type="button" className="dt-secondary" onClick={() => { void start(); }} disabled={active || busy}>Use phone or laptop camera</button><label className="dt-file-button">Choose barcode image<input type="file" accept="image/*" onChange={event => { void fromFile(event.target.files?.[0]); event.target.value = ""; }} disabled={busy} /></label>{(active || busy) && <button type="button" className="dt-secondary" onClick={stop}>Stop scan</button>}</div>
    <div className={`dt-camera${active ? " dt-camera-active" : ""}`}><video ref={video} muted playsInline aria-label="Barcode camera preview" />{active && <p>Hold the complete barcode inside the camera view. Scanning stops after a match.</p>}</div>
    {busy && <p className="dt-status" role="status">{active ? "Starting camera..." : "Reading barcode image..."}</p>}
    {message && <p className="dt-status" role="status">{message}</p>}
    {error && <p className="dt-error" role="alert">{error}</p>}
    <small>Camera access starts only when requested. Images are decoded on this device.</small>
  </section>;
}
